document.addEventListener('DOMContentLoaded', () => {
  const defaultLang = 'vi';
  let currentLang = localStorage.getItem('site_lang') || defaultLang;

  const langBtns = document.querySelectorAll('.lang-btn');

  const updateLanguage = (lang) => {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[key] && translations[key][lang]) {
        // Use innerHTML if the text contains HTML tags like <br>
        if (translations[key][lang].includes('<') || el.innerHTML.includes('<')) {
          el.innerHTML = translations[key][lang];
        } else {
          el.innerText = translations[key][lang];
        }
      }
    });

    // Update placeholders for inputs/textareas
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (translations[key] && translations[key][lang]) {
        el.setAttribute('placeholder', translations[key][lang]);
      }
    });

    // Update active state of language buttons
    langBtns.forEach(btn => {
      if (btn.getAttribute('data-lang') === lang) {
        btn.classList.add('active');
      } else {
        btn.classList.remove('active');
      }
    });

    document.documentElement.lang = lang;
  };

  langBtns.forEach(btn => {
    btn.addEventListener('click', () => {
      currentLang = btn.getAttribute('data-lang');
      localStorage.setItem('site_lang', currentLang);
      updateLanguage(currentLang);
    });
  });

  // Initial load
  updateLanguage(currentLang);
});
